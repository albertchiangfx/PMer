const PDFDocument = require('pdfkit');

function generateInvoicePDF(invoice, items, project, client, res) {
  const doc = new PDFDocument({ margin: 50, size: 'A4' });
  doc.pipe(res);

  // Header
  doc.fontSize(28).font('Helvetica-Bold').fillColor('#111827').text('INVOICE', 50, 50);
  doc.fontSize(11).font('Helvetica').fillColor('#6b7280');
  doc.text(`Invoice #${invoice.invoice_number}`, 50, 90);
  doc.text(`Issued: ${fmtDate(invoice.issued_date)}`, 50, 105);
  if (invoice.due_date) doc.text(`Due: ${fmtDate(invoice.due_date)}`, 50, 120);

  // Status badge
  const statusColors = { draft: '#f59e0b', sent: '#3b82f6', paid: '#10b981', overdue: '#ef4444' };
  const sc = statusColors[invoice.status] || '#6b7280';
  doc.roundedRect(400, 50, 145, 30, 6).fill(sc);
  doc.fontSize(12).font('Helvetica-Bold').fillColor('#ffffff')
    .text(invoice.status.toUpperCase(), 400, 58, { width: 145, align: 'center' });

  // Divider
  doc.moveTo(50, 150).lineTo(545, 150).strokeColor('#e5e7eb').stroke();

  // Bill To
  doc.fillColor('#6b7280').fontSize(9).font('Helvetica-Bold').text('BILL TO', 50, 165);
  doc.fillColor('#111827').fontSize(13).font('Helvetica-Bold').text(client?.name || 'N/A', 50, 180);
  if (client?.contact_email) doc.fontSize(10).font('Helvetica').fillColor('#6b7280').text(client.contact_email, 50, 196);
  if (client?.address) doc.text(client.address, 50, 211, { width: 200 });

  // Project info
  doc.fillColor('#6b7280').fontSize(9).font('Helvetica-Bold').text('PROJECT', 350, 165);
  doc.fillColor('#111827').fontSize(13).font('Helvetica-Bold').text(project?.name || 'N/A', 350, 180);

  // Items table
  const tableTop = 280;
  doc.moveTo(50, tableTop - 10).lineTo(545, tableTop - 10).strokeColor('#e5e7eb').stroke();

  // Table header
  doc.fillColor('#6b7280').fontSize(9).font('Helvetica-Bold');
  doc.text('DESCRIPTION', 50, tableTop);
  doc.text('MEMBER', 220, tableTop);
  doc.text('HOURS', 340, tableTop, { width: 60, align: 'right' });
  doc.text('RATE', 400, tableTop, { width: 60, align: 'right' });
  doc.text('AMOUNT', 460, tableTop, { width: 85, align: 'right' });

  doc.moveTo(50, tableTop + 15).lineTo(545, tableTop + 15).strokeColor('#e5e7eb').stroke();

  let y = tableTop + 25;
  let total = 0;

  for (const item of items) {
    const amount = parseFloat(item.amount) || 0;
    total += amount;

    doc.fillColor('#111827').fontSize(10).font('Helvetica');
    doc.text(item.description || 'Service', 50, y, { width: 165 });
    doc.text(item.member_name || '', 220, y, { width: 115 });
    doc.text(item.hours ? item.hours.toString() : '', 340, y, { width: 60, align: 'right' });
    doc.text(item.rate ? `$${parseFloat(item.rate).toFixed(2)}` : '', 400, y, { width: 60, align: 'right' });
    doc.text(`$${amount.toFixed(2)}`, 460, y, { width: 85, align: 'right' });

    y += 22;
    if (y > 700) { doc.addPage(); y = 50; }
  }

  // Total
  doc.moveTo(50, y + 5).lineTo(545, y + 5).strokeColor('#e5e7eb').stroke();
  y += 20;
  doc.fillColor('#6b7280').fontSize(10).font('Helvetica-Bold').text('TOTAL', 400, y);
  doc.fillColor('#111827').fontSize(16).font('Helvetica-Bold')
    .text(`${invoice.currency || 'USD'} $${total.toFixed(2)}`, 460, y - 3, { width: 85, align: 'right' });

  // Footer
  doc.moveTo(50, 760).lineTo(545, 760).strokeColor('#e5e7eb').stroke();
  doc.fillColor('#9ca3af').fontSize(9).font('Helvetica')
    .text('Generated by Studio PM — 3D Animation Studio Management System', 50, 770, { align: 'center', width: 495 });

  doc.end();
}

function fmtDate(d) {
  if (!d) return '';
  return new Date(d).toLocaleDateString('en-US', { year: 'numeric', month: 'long', day: 'numeric' });
}

module.exports = { generateInvoicePDF };
